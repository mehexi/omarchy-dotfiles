#!/bin/bash
# Copy this PC's Omarchy customization INTO the repo (run on the source PC,
# then commit + push). install.sh does the reverse on any other Omarchy box.
#
# Plugins cloned from upstream (Theme Studio, Tricky Tiles, Softly, Hello Lock)
# are NOT vendored: each carries its own .git and together they are ~80 MB. They
# are listed in externals.txt for install.sh to fetch, and any file of theirs we
# changed is copied into patches/ and laid back over the fresh clone.
set -euo pipefail

REPO="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
SRC="$HOME/.config"
DST="$REPO/config"

# Paths (relative to ~/.config) that make up the customization.
PATHS=(
  omarchy/plugins
  omarchy/bar
  omarchy/bin
  omarchy/branding
  omarchy/extensions
  omarchy/hooks
  omarchy/shell.json
  omarchy/shell.toml
  omarchy/dock.json
  hypr
  fastfetch
  alacritty/alacritty.toml
  foot/foot.ini
  ghostty/config
  kitty/kitty.conf
  btop/btop.conf
  tmux/tmux.conf
)

# Plugins installed from their own git repos: "<plugin id> <git url>".
# Kept out of config/ and re-added by install.sh.
EXTERNALS=(
  "io.github.denonmaryland.theme-studio https://github.com/denonmaryland/omarchy-theme-studio"
  "io.github.denonmaryland.tricky-tiles https://github.com/denonmaryland/omarchy-tricky-tiles"
  "io.github.denonmaryland.softly       https://github.com/denonmaryland/omarchy-softly"
)

# Files inside an external plugin that we changed and want to keep.
PATCHED=(
  "io.github.denonmaryland.theme-studio/helpers/wallpapers.py"
  "io.github.denonmaryland.theme-studio/ThemeStudio.qml"
)

# hypr files that describe THIS machine rather than the look. Never synced:
# install.sh must not overwrite another PC's displays or its autostart.
HYPR_LOCAL=(monitors.lua autostart.lua)

EXCLUDES=(
  --exclude='.git' --exclude='.git/**'
  --exclude='*.bak' --exclude='*.bak.*' --exclude='*.bak2.*'
  --exclude='*.openverse.bak.*'
  --exclude='*.sample' --exclude='*.pre-glass.*' --exclude='*.omarchy-upgrade-*'
  --exclude='__pycache__' --exclude='*.pyc'
)

rm -rf "$DST" "$REPO/local" "$REPO/patches"
mkdir -p "$DST"

for p in "${PATHS[@]}"; do
  [[ -e $SRC/$p ]] || { echo "skip (missing): $p"; continue; }
  mkdir -p "$DST/$(dirname "$p")"
  rsync -a "${EXCLUDES[@]}" "$SRC/$p" "$DST/$(dirname "$p")/"
done

# Drop the externals out of the vendored plugin tree.
for e in "${EXTERNALS[@]}"; do
  rm -rf "$DST/omarchy/plugins/${e%% *}"
done
# Hello Lock ships with denon's dots but this setup uses mehexi.lock instead.
rm -rf "$DST/omarchy/plugins/hello-lock"

# Machine-specific hypr files stay on the machine.
for f in "${HYPR_LOCAL[@]}"; do
  rm -f "$DST/hypr/$f"
done
# Omarchy 4.5 reads the Lua config provider; the .conf files next to it are dead
# leftovers from the pre-Lua layout that nothing sources (monitors.conf in
# particular sat at a stale scale). Shipping them would only mislead.
rm -f "$DST"/hypr/*.conf
# Generated by the Touchpad drawer on first run; laptop-only.
rm -f "$DST/hypr/touchpad-control.lua"

# Our changes to upstream plugin files.
for f in "${PATCHED[@]}"; do
  if [[ -e $SRC/omarchy/plugins/$f ]]; then
    mkdir -p "$REPO/patches/$(dirname "$f")"
    cp -a "$SRC/omarchy/plugins/$f" "$REPO/patches/$f"
  else
    echo "warning: patched file missing: $f" >&2
  fi
done

printf '%s\n' "${EXTERNALS[@]}" | sed 's/  */ /g' > "$REPO/externals.txt"

# Helper scripts denon's dots install outside ~/.config.
for p in share/omarchy-glass share/omarchy-recess share/denon-agent-usage share/touchpad-control \
         bin/denon-agent-usage-update bin/denon-wifi-other bin/hypr-all-full-width bin/hypr-smart-focus; do
  [[ -e $HOME/.local/$p ]] || continue
  mkdir -p "$REPO/local/$(dirname "$p")"
  rsync -a "${EXCLUDES[@]}" "$HOME/.local/$p" "$REPO/local/$(dirname "$p")/"
done

# Installed git themes: "<dir-name> <clone-url>" per line.
: > "$REPO/themes.txt"
for t in "$SRC"/omarchy/themes/*/; do
  name=$(basename "$t")
  url=$(git -C "$t" remote get-url origin 2>/dev/null || true)
  if [[ -n $url ]]; then
    echo "$name $url" >> "$REPO/themes.txt"
  else
    echo "warning: theme '$name' is not a git clone, not synced" >&2
  fi
done

# Current look.
STATE="$HOME/.local/state/omarchy/current"
bg=$(readlink "$STATE/background" 2>/dev/null || true)
cat > "$REPO/state.env" <<EOF
THEME="$(cat "$STATE/theme.name" 2>/dev/null)"
BACKGROUND="$(basename "${bg:-}")"
FONT="$(omarchy font current 2>/dev/null || true)"
ICON_THEME="$(gsettings get org.gnome.desktop.interface icon-theme 2>/dev/null | tr -d "'")"
EOF

echo "Synced into $REPO. Review with: git -C '$REPO' status"
